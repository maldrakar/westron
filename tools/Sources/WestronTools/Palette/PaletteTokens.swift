import Foundation

/// The palette generator (decisions/0012): from `tokens/palette.json` it writes the color ramps of each theme as
/// DTCG primitives, `tokens/primitive/color.<theme>.tokens.json`, which the resolver's theme contexts merge in. A
/// high-contrast file holds only the colors that differ from its base theme.
///
/// It runs before the generators that read the tokens; `tools/westron generate` repeats its passes until nothing
/// changes, so the platforms are generated from the ramps just written.
public struct PaletteTokens: Generator {
    public let name = "tokens-palette"
    /// The palette source, relative to the repository root.
    public let sourceFile: String

    public init(sourceFile: String = PaletteSource.defaultFile) {
        self.sourceFile = sourceFile
    }

    /// The token file of a theme, relative to the repository root.
    public static func file(_ theme: String) -> String { "tokens/primitive/color.\(theme).tokens.json" }

    public func run() throws -> [GeneratedFile] {
        try Self.files(for: PaletteSource.load(file: sourceFile), source: sourceFile)
    }

    /// The four token files, in the order of `PaletteSolver.themes`.
    public static func files(for palette: PaletteSource, source: String) throws -> [GeneratedFile] {
        let solved = try PaletteSolver.solve(palette)
        return PaletteSolver.themes.map { theme in
            GeneratedFile(path: file(theme), contents: tokens(solved[theme]!, theme: theme, source: source))
        }
    }

    /// A token file: one group per ramp, in the solver's order, one token per line. Each color is written in OKLCH
    /// at the precision that converts back to its hex, with the hex as the fallback.
    static func tokens(_ entries: [PaletteSolver.Entry], theme: String, source: String) -> String {
        let highContrast = theme.hasSuffix("-hc")
        let what =
            highContrast
            ? "The colors of the \(theme) theme that differ from the \(theme.dropLast(3)) theme, merged over it."
            : "The color ramps of the \(theme) theme."
        let description =
            "Generated by `tools/westron generate` from \(source); do not edit. \(what) Components never use these "
            + "directly; semantic colors alias them (decisions/0010, 0012)."
        var groups: [(name: String, lines: [String])] = []
        for entry in entries {
            let line = "\"\(entry.path[1])\": {\"$value\": \(value(entry.color))}"
            if let last = groups.indices.last, groups[last].name == entry.path[0] {
                groups[last].lines.append(line)
            } else {
                groups.append((entry.path[0], [line]))
            }
        }
        var text = "{\n  \"color\": {\n    \"$type\": \"color\",\n    \"$description\": \(quoted(description))"
        for group in groups {
            text += ",\n    \"\(group.name)\": {\n"
            text += group.lines.map { "      " + $0 }.joined(separator: ",\n")
            text += "\n    }"
        }
        return text + "\n  }\n}\n"
    }

    /// `{"colorSpace": "oklch", "components": [L, C, H], "hex": "#RRGGBB"}`, with `"none"` for the hue of a gray.
    static func value(_ color: RGB) -> String {
        let hex = color.hex
        // Every 8-bit sRGB color round-trips at this precision (OKLCHPrecision.hexRoundTrip).
        let oklch = try! OKLCH(hex: hex)
        let precision = OKLCHPrecision.hexRoundTrip
        let components = [
            DecimalFormat.fixed(oklch.l, decimals: precision.l, trimmingZeros: true),
            DecimalFormat.fixed(oklch.c, decimals: precision.c, trimmingZeros: true),
            oklch.h.map { DecimalFormat.fixed($0, decimals: precision.h, trimmingZeros: true) } ?? "\"none\"",
        ]
        return
            "{\"colorSpace\": \"oklch\", \"components\": [\(components.joined(separator: ", "))], \"hex\": \"\(hex)\"}"
    }

    static func quoted(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
